<?php

declare(strict_types=1);

namespace Kanin\Database;

use PDO;
use PDOStatement;

/**
 * A thin, friendly wrapper around PHP's PDO.
 *
 * It opens the database connection only when it is first needed ("lazy"),
 * always uses prepared statements with bound values, and hands out
 * QueryBuilder instances through table().
 */
class Connection
{
    /** Drivers KaninPHP knows how to build a DSN for. */
    private const DRIVERS = ['sqlite', 'mysql', 'pgsql'];

    /** Default TCP ports for the network drivers. */
    private const DEFAULT_PORTS = ['mysql' => 3306, 'pgsql' => 5432];

    private array $config;

    private ?PDO $pdo = null;

    /**
     * Create a connection from a config array.
     *
     * Keys: driver (sqlite|mysql|pgsql), database, host, port, username,
     * password and charset (defaults to utf8mb4). Nothing connects yet.
     */
    public function __construct(array $config)
    {
        $driver = (string) ($config['driver'] ?? '');

        if (! in_array($driver, self::DRIVERS, true)) {
            throw new \InvalidArgumentException("Unsupported database driver [{$driver}].");
        }

        $this->config = $config + ['charset' => 'utf8mb4'];
    }

    /** Get the underlying PDO object, connecting on the first call. */
    public function getPdo(): PDO
    {
        if ($this->pdo === null) {
            $this->pdo = $this->connect();
        }

        return $this->pdo;
    }

    /** The configured driver name: "sqlite", "mysql" or "pgsql". */
    public function getDriverName(): string
    {
        return $this->config['driver'];
    }

    /** Run a SELECT and return every row as an associative array. */
    public function select(string $sql, array $bindings = []): array
    {
        return $this->run($sql, $bindings)->fetchAll();
    }

    /** Run a SELECT and return the first row, or null when there is none. */
    public function selectOne(string $sql, array $bindings = []): ?array
    {
        $row = $this->run($sql, $bindings)->fetch();

        return is_array($row) ? $row : null;
    }

    /** Run an INSERT statement. Returns true on success. */
    public function insert(string $sql, array $bindings = []): bool
    {
        return $this->statement($sql, $bindings);
    }

    /** Run an UPDATE statement and return the number of affected rows. */
    public function update(string $sql, array $bindings = []): int
    {
        return $this->run($sql, $bindings)->rowCount();
    }

    /** Run a DELETE statement and return the number of deleted rows. */
    public function delete(string $sql, array $bindings = []): int
    {
        return $this->run($sql, $bindings)->rowCount();
    }

    /** Run any other prepared statement (CREATE TABLE, ...). Returns true on success. */
    public function statement(string $sql, array $bindings = []): bool
    {
        $this->run($sql, $bindings);

        return true;
    }

    /**
     * Run raw SQL without bindings (may contain several statements).
     *
     * Only use this with trusted SQL such as database/seed.sql,
     * never with anything that came from a request.
     */
    public function unprepared(string $sql): bool
    {
        $this->getPdo()->exec($sql);

        return true;
    }

    /** The id generated by the most recent INSERT, as a string. */
    public function lastInsertId(): string
    {
        return (string) $this->getPdo()->lastInsertId();
    }

    /**
     * Run the callback inside a transaction.
     *
     * Commits when the callback returns, rolls back and re-throws when it
     * throws. The callback receives this connection; its return value is returned.
     */
    public function transaction(\Closure $callback): mixed
    {
        $pdo = $this->getPdo();
        $pdo->beginTransaction();

        try {
            $result = $callback($this);
            $pdo->commit();

            return $result;
        } catch (\Throwable $e) {
            if ($pdo->inTransaction()) {
                $pdo->rollBack();
            }

            throw $e;
        }
    }

    /** Start a fluent query against a table: $db->table('users')->where('id', 1)->first(). */
    public function table(string $table): QueryBuilder
    {
        return new QueryBuilder($this, $table);
    }

    /** Prepare the SQL, bind every value with a matching PDO type and execute it. */
    private function run(string $sql, array $bindings): PDOStatement
    {
        $statement = $this->getPdo()->prepare($sql);

        foreach ($bindings as $key => $value) {
            $parameter = is_int($key) ? $key + 1 : ':' . ltrim((string) $key, ':');
            $statement->bindValue($parameter, $value, $this->pdoType($value));
        }

        $statement->execute();

        return $statement;
    }

    /** Pick the PDO parameter type for a PHP value. */
    private function pdoType(mixed $value): int
    {
        return match (true) {
            is_int($value) => PDO::PARAM_INT,
            is_bool($value) => PDO::PARAM_BOOL,
            $value === null => PDO::PARAM_NULL,
            default => PDO::PARAM_STR,
        };
    }

    /** Open the real PDO connection. */
    private function connect(): PDO
    {
        $pdo = new PDO(
            $this->dsn(),
            $this->config['username'] ?? null,
            $this->config['password'] ?? null,
            [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                PDO::ATTR_EMULATE_PREPARES => false,
            ],
        );

        if ($this->getDriverName() === 'sqlite') {
            $pdo->exec('PRAGMA foreign_keys = ON');
        }

        return $pdo;
    }

    /** Build the PDO DSN string for the configured driver. */
    private function dsn(): string
    {
        $driver = $this->getDriverName();
        $database = (string) ($this->config['database'] ?? '');

        if ($driver === 'sqlite') {
            return 'sqlite:' . $database;
        }

        $host = (string) ($this->config['host'] ?? '127.0.0.1');
        $port = (int) ($this->config['port'] ?? self::DEFAULT_PORTS[$driver]);

        if ($driver === 'mysql') {
            return "mysql:host={$host};port={$port};dbname={$database};charset={$this->config['charset']}";
        }

        return "pgsql:host={$host};port={$port};dbname={$database}";
    }
}
